/**
 * Порядок сообщений: стабильное (инструкция + резюме, в hybrid-режиме — ещё
 * и скелет) идёт первым как system-сообщение, волатильное (текст вакансии) —
 * вторым, как user-сообщение. Это просто гигиена расположения: стабильный
 * префикс первым не мешает и кое-где помогает — некоторые провайдеры кешируют
 * запросы на своей стороне без каких-либо явных маркеров от нас. Формального
 * контроля над этим у нас нет: OpenRouter не поддерживает Anthropic-специфичный
 * `cache_control`, поэтому мы его не отправляем и не обещаем экономию на кеше.
 */
export function buildPrompt(input: LetterInput): PromptParts {
  const instruction = input.mode === 'full' ? instructionFull(input.role) : instructionHybrid(input.role);
  const stable = input.mode === 'full'
    ? `${instruction}\n\n=== РЕЗЮМЕ ===\n${input.resume}`
    : `${instruction}\n\n=== РЕЗЮМЕ ===\n${input.resume}\n\n=== СКЕЛЕТ ===\n${input.template}`;

  const v = input.vacancy;
  const volatile = [
    `Вакансия: ${v.title}`,
    `Компания: ${v.company}`,
    `Локация: ${v.geo}`,
    input.matched.length > 0 ? `Совпавшие ключевые темы: ${input.matched.join(', ')}` : '',
    '',
    '=== ТЕКСТ ВАКАНСИИ ===',
    v.description,
  ].filter((s) => s !== '').join('\n');

  return {
    messages: [
      { role: 'system', content: stable },
      { role: 'user', content: volatile },
    ],
  };
}

const EMPTY_RESULT = { letter: '', mode: 'none' as const };

/**
 * Пробует модели из `options.models` по порядку через OpenRouter. Любой сбой —
 * нет ключа, сетевая ошибка, HTTP-ошибка, ответ без текста — переходит
 * к следующей модели, а не бросает. Если ни одна модель не ответила,
 * возвращается пустое письмо с mode 'none': запись всё равно попадёт
 * в очередь, человек увидит её пустой и напишет письмо руками. Потеря
 * вакансии из-за сбоя генерации — ровно то, что этот контракт не даёт
 * случиться.
 */
/**
 * Утверждения, которых в письме быть не должно, потому что они не подтверждены
 * резюме и прямо противоречат тому, что пользователь о себе сказал.
 *
 * Это не стилистика, а защита от вранья. Инструкция уже запрещает выдумывать
 * факты и преувеличивать, но 2026-08-30 модель всё равно написала «создавал
 * отчётные запросы с JOIN, оконными функциями и агрегатами». В резюме нет ни
 * JOIN, ни оконных функций: там SQL в списке инструментов и PostgreSQL как
 * выбор хранилища. Пользователь отдельно сказал, что SQL читает и правит, но
 * сложные запросы с нуля не пишет, и что контракты API не проектирует.
 *
 * Цена ошибки несимметрична. Пропущенное слово стоит одной переписанной
 * врезки; пропущенная выдумка всплывает на собеседовании, где за неё отвечает
 * человек, а не модель. Поэтому такое письмо считается негодным, и цепочка
 * пробует снова.
 *
 * Список намеренно узкий и конкретный: он ловит заявленную ГЛУБИНУ навыка,
 * а не сам навык. Слово «SQL» разрешено — запрещено «писал оконные функции».
 */
const FORBIDDEN_CLAIMS: ReadonlyArray<{ re: RegExp; what: string }> = [
  { re: /оконны[а-яё]*\s+функци/i, what: 'оконные функции' },
  { re: /\bJOIN\b/i, what: 'JOIN' },
  { re: /\bCTE\b/i, what: 'CTE' },
  { re: /подзапрос/i, what: 'подзапросы' },
  { re: /хранимы[а-яё]*\s+процедур/i, what: 'хранимые процедуры' },
  { re: /(проектирова|разрабатыва)[а-яё]*\s+(контракт|API)/i, what: 'проектирование контрактов API' },
  /**
   * Стем "писа" отдельно от "проектирова"/"разрабатыва" выше: он короче и
   * встречается как ПОДСТРОКА внутри приставочных форм того же глагола —
   * "на|писа|л", "рас|писа|л", "под|писа|л" — где кириллица не даёт
   * воспользоваться \b (см. шапку core/screening.ts, тот же класс проблемы).
   * Без лукэраунда "написал API-документацию" (читает и описывает чужой API,
   * подтверждено резюме) ловилось наравне с "писал контракты API" (реальная
   * выдумка) — регэксп совпадал внутри "на+писа", не заметив приставку.
   * (?<![а-яёА-ЯЁ]) требует, чтобы ПЕРЕД "писа" не было кириллической буквы —
   * то есть матчит только слово, начинающееся ровно с этого стема
   * ("писал", "пишет"), а не производные с приставкой.
   */
  { re: /(?<![а-яёА-ЯЁ])писа[а-яё]*\s+(контракт|API)/i, what: 'проектирование контрактов API' },
];

/** Первое найденное запрещённое утверждение, либо null. */
export function findForbiddenClaim(text: string): string | null {
  for (const { re, what } of FORBIDDEN_CLAIMS) {
    if (re.test(text)) return what;
  }
  return null;
}

/** Куски скелета, по которым видно, что модель их не заполнила. */
const PLACEHOLDER = /\{\{\s*(HOOK|FIT|TITLE|COMPANY)\s*\}\}/;

/**
 * Годен ли ответ модели как письмо.
 *
 * Проверяется две вещи, обе — про гибридный режим, где модель должна была
 * заполнить {{HOOK}} и {{FIT}}:
 *
 * 1. В тексте не осталось незаполненных плейсхолдеров.
 * 2. Текст не является скелетом, из которого плейсхолдеры просто вырезали.
 *    Слабые модели делают именно это: возвращают синтаксически чистое письмо,
 *    в котором нет ни слова про конкретную вакансию. Сравниваем со скелетом,
 *    выкинув из него плейсхолдеры и пробелы: если совпало, модель ничего не
 *    добавила.
 */
export function isUsableLetter(text: string, input: LetterInput): boolean {
  const trimmed = text.trim();
  if (trimmed === '') return false;
  if (PLACEHOLDER.test(trimmed)) return false;
  // Письмо, приписывающее человеку то, чего он не умеет, отправлять нельзя —
  // отвечать за это ему на собеседовании. См. FORBIDDEN_CLAIMS.
  if (findForbiddenClaim(trimmed) !== null) return false;
  if (input.mode !== 'hybrid') return true;

  // Раньше здесь ещё стоял s.replace(PLACEHOLDER, ' ') первым шагом — PLACEHOLDER
  // без /g заменяет только ПЕРВОЕ вхождение {{HOOK|FIT|TITLE|COMPANY}}, а
  // следующий .replace(/\{\{[^}]*\}\}/g, ...) глобален и ловит ЛЮБОЕ {{...}},
  // включая то же самое первое вхождение — то есть полностью его поглощает.
  // Первый вызов не мог повлиять на результат ни при каком входе; убран.
  const squash = (s: string): string =>
    s.replace(/\{\{[^}]*\}\}/g, ' ').replace(/\s+/g, ' ').trim();
  if (squash(trimmed) === squash(input.template)) return false;

  // Постоянные куски скелета обязаны дойти дословно. Скелет — утверждённый
  // человеком голос, модели поручено только заполнить врезки. Живой прогон
  // 2026-08-30 показал, что слабая модель вместо этого переписывает скелет и
  // портит его: "интервьюирую" превратилось в "intervieuирую", "защищаю" в
  // "защищай". Такое письмо выглядит заполненным и гейт выше проходит, но
  // отправлять его нельзя.
  const out = squash(trimmed);
  for (const chunk of input.template.split(/\{\{[^}]*\}\}/)) {
    const fixed = squash(chunk);
    // Короткие огрызки между плейсхолдерами не проверяем: на них ложные
    // срабатывания от разницы в пунктуации.
    if (fixed.length < 40) continue;
    if (!out.includes(fixed)) return false;
  }
  return true;
}

export async function generateLetter(
  input: LetterInput,
  options: GenerateLetterOptions,
): Promise<{ letter: string; mode: LetterMode; failure?: string }> {
  const r = await complete(buildPrompt(input).messages, options, (text) =>
    // Внешне правдоподобное письмо бывает бесполезным: в гибридном режиме
    // слабые модели вырезают {{HOOK}} и {{FIT}} вместо того, чтобы их
    // заполнить, портят скелет или выдумывают факт. Такой ответ — неудача,
    // пробуем следующую модель (см. isUsableLetter).
    isUsableLetter(text, input)
      ? null
      : 'письмо не прошло проверку (вырезаны вставки, испорчен скелет или выдуман факт)');
  return r.ok ? { letter: r.text, mode: input.mode } : { ...EMPTY_RESULT, failure: r.failure };
}
