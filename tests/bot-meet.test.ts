import { describe, it, expect } from 'vitest';
import { parseMeetTime, formatMeetTime } from '../src/bot/meet.js';

/** Воскресенье, 20 сентября 2026, 12:00 по местному времени. */
const now = new Date(2026, 8, 20, 12, 0);

/** «ГГГГ-ММ-ДД чч:мм» — ожидание читается глазами, а не считается кодом под тестом. */
const stamp = (d: Date): string => {
  const two = (n: number): string => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${two(d.getMonth() + 1)}-${two(d.getDate())} ${two(d.getHours())}:${two(d.getMinutes())}`;
};

const parsed = (text: string, at: Date = now): string | null => {
  const r = parseMeetTime(text, at);
  return r.ok ? stamp(r.at) : null;
};

describe('parseMeetTime — понимает рекрутёра, а не формат', () => {
  // Примеры владельца (2026-10-05) и прежний формат `дд.мм;чч:мм`, который
  // обязан продолжать работать.
  it.each<[string, string]>([
    ['10 октября в 15:00', '2026-10-10 15:00'],
    ['10.10 в 15:00', '2026-10-10 15:00'],
    ['10.10 в час дня', '2026-10-10 13:00'],
    ['07.10;15:30', '2026-10-07 15:30'],
    ['7.10 15.30', '2026-10-07 15:30'],
    ['07.10, 15:30', '2026-10-07 15:30'],
    ['07,10 15.30', '2026-10-07 15:30'],
    ['можно 07.10;15:30 ?', '2026-10-07 15:30'],
  ])('«%s» → %s', (text, want) => {
    expect(parsed(text)).toBe(want);
  });

  it.each<[string, string]>([
    ['10 октября, 15:00', '2026-10-10 15:00'],
    ['10 окт 15:00', '2026-10-10 15:00'],
    ['10-го октября в 15:00', '2026-10-10 15:00'],
    ['10 октября 2026 в 15:00', '2026-10-10 15:00'],
    ['15:00 10.10', '2026-10-10 15:00'],
    ['в 10 утра 10 октября', '2026-10-10 10:00'],
    ['10/10 в 15:00', '2026-10-10 15:00'],
    ['10.10.2027 в 15:00', '2027-10-10 15:00'],
    ['10.10.26 15:00', '2026-10-10 15:00'],
    ['2026-10-10 15:00', '2026-10-10 15:00'],
    ['ДОБРЫЙ ДЕНЬ! Давайте 10 Октября в 15:00 по Москве, подойдёт?', '2026-10-10 15:00'],
    ['10.10 в 15:00, мой телефон +7 999 123-45-67', '2026-10-10 15:00'],
  ])('дата и запись: «%s» → %s', (text, want) => {
    expect(parsed(text)).toBe(want);
  });

  // Часы без «:» — самое частое, что пишут с телефона. Без «утра/дня/вечера»
  // часы 1–7 читаются как дневные: собеседований в три часа ночи не бывает.
  it.each<[string, string]>([
    ['10.10 в 3 часа дня', '2026-10-10 15:00'],
    ['10.10 в два часа дня', '2026-10-10 14:00'],
    ['10.10 в 10 утра', '2026-10-10 10:00'],
    ['10.10 в 8 вечера', '2026-10-10 20:00'],
    ['10.10 в 2', '2026-10-10 14:00'],
    ['10.10 в 9', '2026-10-10 09:00'],
    ['10.10 в 12', '2026-10-10 12:00'],
    ['10.10 в полдень', '2026-10-10 12:00'],
    ['10.10 в 12 ночи', '2026-10-10 00:00'],
    ['10.10 в 15 часов', '2026-10-10 15:00'],
    ['10.10 в 15ч', '2026-10-10 15:00'],
    ['10.10 в 3:30 дня', '2026-10-10 15:30'],
    ['10.10 в 15 часов 30 минут', '2026-10-10 15:30'],
    ['10.10 в 15-30', '2026-10-10 15:30'],
    ['10.10 в 15.00', '2026-10-10 15:00'],
    ['10.10 с 15:00 до 16:00', '2026-10-10 15:00'],
    // Ведущий ноль — это сутки, а не «три часа дня».
    ['10.10 в 03:00', '2026-10-10 03:00'],
  ])('время: «%s» → %s', (text, want) => {
    expect(parsed(text)).toBe(want);
  });

  // now — воскресенье 20.09, 12:00.
  it.each<[string, string]>([
    ['завтра в 15:00', '2026-09-21 15:00'],
    ['ЗАВТРА В 15:00', '2026-09-21 15:00'],
    ['послезавтра в 11', '2026-09-22 11:00'],
    ['послезавтра в час дня', '2026-09-22 13:00'],
    ['через 3 дня в 15:00', '2026-09-23 15:00'],
    ['через три дня в 15:00', '2026-09-23 15:00'],
    ['в пятницу в 14:30', '2026-09-25 14:30'],
    ['во вторник в 11', '2026-09-22 11:00'],
    ['в пт в 15', '2026-09-25 15:00'],
    // Сокращение и просто название дня, без «в».
    ['пт 11:00', '2026-09-25 11:00'],
    ['Вторник, 13.10, 15:00', '2026-10-13 15:00'],
    ['в четверг в три часа дня', '2026-09-24 15:00'],
    ['сегодня в 18:00', '2026-09-20 18:00'],
    // Сегодняшний день недели: позже текущего часа — сегодня, раньше — через неделю.
    ['в воскресенье в 18:00', '2026-09-20 18:00'],
    ['в воскресенье в 10:00', '2026-09-27 10:00'],
    ['20 числа в 18:00', '2026-09-20 18:00'],
    ['10 числа в 15:00', '2026-10-10 15:00'],
    // Дата без года: ближайшая в будущем, прошедшая в этом году — значит следующий.
    ['05.01;10:00', '2027-01-05 10:00'],
    ['20.09;18:00', '2026-09-20 18:00'],
  ])('относительно сегодня: «%s» → %s', (text, want) => {
    expect(parsed(text)).toBe(want);
  });

  it('29 февраля високосного года принимается', () => {
    expect(parsed('29.02;10:00', new Date(2027, 11, 1))).toBe('2028-02-29 10:00');
  });

  it.each<[string, 'unclear' | 'no-time' | 'past']>([
    ['', 'unclear'],
    ['привет', 'unclear'],
    ['в 15:00', 'unclear'],
    ['31.02 в 10:00', 'unclear'],
    ['31.04;10:00', 'unclear'],
    ['07.10;25:00', 'unclear'],
    ['07.13;10:00', 'unclear'],
    ['10.10 в 25', 'unclear'],
    ['10 октября', 'no-time'],
    ['10.10', 'no-time'],
    ['в пятницу', 'no-time'],
    ['давайте в среду', 'no-time'],
    ['завтра', 'no-time'],
    ['сегодня в 9', 'past'],
    ['10.10.2025 в 15:00', 'past'],
  ])('отказ: «%s» — %s', (text, reason) => {
    expect(parseMeetTime(text, now)).toEqual({ ok: false, reason });
  });
});

describe('parseMeetTime — неделя и ложные срабатывания', () => {
  /** Понедельник, 5 октября 2026, 17:10. */
  const monday = new Date(2026, 9, 5, 17, 10);

  it.each<[string, string]>([
    ['во вторник в 11', '2026-10-06 11:00'],
    ['в понедельник в 18:00', '2026-10-05 18:00'],
    ['в понедельник в 10:00', '2026-10-12 10:00'],
    // «На следующей неделе» сдвигает день недели за ближайший понедельник.
    ['на следующей неделе во вторник в 11', '2026-10-13 11:00'],
    ['на следующей неделе в понедельник в 11', '2026-10-12 11:00'],
    ['давайте на следующей неделе в пятницу, в 15:00', '2026-10-16 15:00'],
  ])('с понедельника: «%s» → %s', (text, want) => {
    expect(parsed(text, monday)).toBe(want);
  });

  it.each<[string, 'unclear' | 'no-time']>([
    // «в 2» здесь не время: после него «раза».
    ['10.10, зарплата в 2 раза выше', 'no-time'],
    // Длинное число — телефон, а не час.
    ['10.10, звоните 89991234567', 'no-time'],
    // Время есть, даты нет.
    ['через 2 часа', 'unclear'],
    ['на следующей неделе в 15:00', 'unclear'],
  ])('не выдумывает время: «%s» — %s', (text, reason) => {
    expect(parseMeetTime(text, monday)).toEqual({ ok: false, reason });
  });
});

describe('подтверждение рекрутёру — дата и время словами', () => {
  it.each<[string, string]>([
    ['07.10;15:30', '7 октября (среда), 15:30'],
    ['10.10 в час дня', '10 октября (суббота), 13:00'],
    ['завтра в 09:05', '21 сентября (понедельник), 09:05'],
    // Чужой год называется явно: «05.01» в сентябре — это январь следующего.
    ['05.01;10:00', '5 января 2027 (вторник), 10:00'],
  ])('«%s» → «%s»', (text, want) => {
    const r = parseMeetTime(text, now);
    expect(r.ok && r.pretty).toBe(want);
  });

  it('formatMeetTime: тот же текст отдаёт пинг владельцу по сохранённому времени', () => {
    expect(formatMeetTime(new Date(2026, 9, 21, 21, 22), new Date(2026, 9, 5, 17, 7)))
      .toBe('21 октября (среда), 21:22');
  });
});
