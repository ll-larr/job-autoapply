import { describe, it, expect } from 'vitest';
import { allowedNumbers, validateAnswer } from '../src/core/interview.js';

const allowed = allowedNumbers([
  'Сократил трудозатраты с 76 до 11 часов в месяц, на 85,5%',
  'Зарплатная вилка 280–360',
  'Расскажите про опыт с 2024 года',
]);

describe('validateAnswer', () => {
  it('пропускает ответ с числами из источников', () => {
    expect(validateAnswer('С 76 до 11 часов, это 85,5%, с 2024 года.', { allowed })).toBeNull();
  });

  it('режет выдуманное число', () => {
    expect(validateAnswer('Сократил примерно на 90%.', { allowed }))
      .toBe('выдуманное число: 90');
  });

  it('режет сдвинутый год', () => {
    expect(validateAnswer('Работал там с 2023 года.', { allowed }))
      .toBe('выдуманное число: 2023');
  });

  it('пустой ответ не годится', () => {
    expect(validateAnswer('   ', { allowed })).toBe('пустой ответ');
  });

  it('слишком длинный ответ не годится', () => {
    const long = 'а'.repeat(1501);
    expect(validateAnswer(long, { allowed })).toBe('длиннее 1500 символов');
  });

  it('режет маркер автомата', () => {
    expect(validateAnswer('Как языковая модель, я не могу ответить.', { allowed }))
      .toBe('маркер автомата');
  });

  it('режет утечку секрета', () => {
    expect(validateAnswer('Ключ sk-abcdefgh12345 лежит в .env', { allowed }))
      .toBe('в ответе ключ');
  });

  it('ММ.ГГГГ дата в ответе пропускает, если компоненты разрешены', () => {
    const allowedWithDateParts = allowedNumbers(['Пробел в занятости 07–12.2025']);
    expect(validateAnswer('Не было работы с 07.2025 по 12.2025.', { allowed: allowedWithDateParts }))
      .toBeNull();
  });

  it('число с хвостовыми нулями пропускает, если основание разрешено', () => {
    const allowedWithTrailing = allowedNumbers(['85,5%']);
    expect(validateAnswer('это 85,50%', { allowed: allowedWithTrailing }))
      .toBeNull();
  });

  it('сумма с разрядами «280 000» проходит, если в источнике та же сумма словами «280–360 тысяч» (H1)', () => {
    const withUnit = allowedNumbers(['Зарплатная вилка 280–360 тысяч']);
    expect(validateAnswer('Ожидаю от 280 000 до 360 000 рублей.', { allowed: withUnit })).toBeNull();
  });

  it('ноль больше не разрешён всегда: хвостом суммы он не бывает, а сам по себе — число (H1)', () => {
    expect(validateAnswer('Было 0 инцидентов.', { allowed })).toBe('выдуманное число: 0');
  });

  it('частые HTTP-коды разрешены всегда (I3)', () => {
    expect(validateAnswer('Проверял коды ответов 200, 400 и 500.', { allowed })).toBeNull();
    expect(validateAnswer('Разбирал 201, 204, 301, 302, 304, 401, 403, 404, 409, 422, 429, 502, 503 и 504.', { allowed }))
      .toBeNull();
  });

  it('число вне белого списка и вне HTTP-кодов по-прежнему режется', () => {
    expect(validateAnswer('Возвращал код 418.', { allowed })).toBe('выдуманное число: 418');
  });

  it('«Как ИИ» и «я бот» на кириллице ловятся: граница слова в JS-регэкспе только латинская (I4)', () => {
    expect(validateAnswer('Как ИИ, я отвечаю за кандидата.', { allowed })).toBe('маркер автомата');
    expect(validateAnswer('Отвечаю как ИИ', { allowed })).toBe('маркер автомата');
    expect(validateAnswer('Я бот, отвечаю за кандидата.', { allowed })).toBe('маркер автомата');
  });

  it('слово, которое лишь начинается с «бот», — не маркер (I4)', () => {
    expect(validateAnswer('Вчера я ботинки купил.', { allowed })).toBeNull();
    expect(validateAnswer('По первому образованию я ботаник.', { allowed })).toBeNull();
  });

  it('режет приписанный навык', () => {
    expect(validateAnswer('Писал JOIN и CTE каждый день.', { allowed }))
      .toMatch(/^выдуман навык:/);
  });
});

describe('validateAnswer: зарплата сверяется по величине (H1)', () => {
  // Настоящая строка data/facts.md владельца на 2026-09-26 и строка «как в резюме».
  const salary = allowedNumbers([
    'Зарплатная вилка: 180–260 тысяч рублей на руки. Конкретная цифра зависит от грейда.',
    'Опыт бизнес-анализа — 3 года, из них 1.5 года в Озон Банке, более 1 млн клиентов.',
    'Какие у вас зарплатные ожидания?',
  ]);

  it.each([
    'Ориентируюсь на 180–260 тысяч на руки.',
    'от 180 000 до 260 000 рублей',
    '180 тыс.',
    'коды ответов 200, 400 и 500',
  ])('правда проходит: «%s»', (answer) => {
    expect(validateAnswer(answer, { allowed: salary })).toBeNull();
  });

  it.each([
    ['Ожидаю от 400 000 рублей.', '400000'],
    // С FU-6 слово о деньгах снимает исключение для HTTP-кодов: режется уже сырое 200 и 500.
    ['Рассчитываю на 200–400 тысяч.', '200'],
    ['Хочу 500 тысяч на руки.', '500'],
    ['Ожидаю 3 000 000 в год.', '3000000'],
    ['3 млн', '3000000'],
  ])('выдуманная сумма режется: «%s»', (answer, number) => {
    expect(validateAnswer(answer, { allowed: salary })).toBe(`выдуманное число: ${number}`);
  });
});

describe('validateAnswer: другие записи сумм и HTTP-коды рядом с деньгами (FU-6)', () => {
  // Строка фактов владельца и строки «как в резюме»: проценты, даты, стаж.
  const real = allowedNumbers([
    'Зарплатная вилка: 180–260 тысяч рублей на руки. Конкретная цифра зависит от грейда.',
    'Озон Банк, бизнес-аналитик 10\\2024 - 07\\2025, опыт 3 года.',
    'Сократил трудозатраты на 85,5%, время инвентаризации на 87,5%, доступность ≥99,5%.',
    'Какие у вас зарплатные ожидания?',
  ]);

  it.each([
    ['Ожидаю 400.000 рублей.', '400000'],
    ['Ожидаю 400,000 рублей.', '400000'],
    ['Ожидаю 500,000 руб.', '500000'],
    ['Рассчитываю на 200,000–400,000 рублей.', '200000'],
    ['Ожидаю 400 тр.', '400000'],
  ])('выдуманная сумма в другой записи режется: «%s»', (answer, number) => {
    expect(validateAnswer(answer, { allowed: real })).toBe(`выдуманное число: ${number}`);
  });

  it.each([
    'Ориентируюсь на 180–260 тысяч на руки.',
    'от 180 000 до 260 000 рублей',
    '180 тыс.',
    'коды ответов 200, 400 и 500',
    'Сократил трудозатраты на 85,5%.',
    'Время инвентаризации сократил на 87,5%.',
    'Доступность системы — ≥99,5%.',
    'В Озон Банке работал до 07.2025.',
  ])('правда проходит: «%s»', (answer) => {
    expect(validateAnswer(answer, { allowed: real })).toBeNull();
  });

  it('рядом со словом о деньгах HTTP-код больше не пропуск: «Ожидаю 400 рублей», «вилка 200–260»', () => {
    expect(validateAnswer('Ожидаю 400 рублей.', { allowed: real })).toBe('выдуманное число: 400');
    expect(validateAnswer('Моя вилка 200–260.', { allowed: real })).toBe('выдуманное число: 200');
    expect(validateAnswer('Оклад 500, премия отдельно.', { allowed: real })).toBe('выдуманное число: 500');
    expect(validateAnswer('Доход 404 ₽ в день.', { allowed: real })).toBe('выдуманное число: 404');
  });

  it('без слов о деньгах HTTP-коды по-прежнему разрешены', () => {
    expect(validateAnswer('Разбирал ответы 404 и 502 от шлюза.', { allowed: real })).toBeNull();
  });

  // Как в настоящем резюме: 400 и 80 в нём есть («400 автотестов», «на 80%»),
  // так что «400к» и «80к» режутся только по величине.
  const withResume = new Set([...real, ...allowedNumbers(['Внедрил 400 автотестов, снизил потери на 80%.'])]);

  it.each([
    ['Ожидаю 200к–260к.', '200000'],
    ['Ожидаю от 200к до 260к.', '200000'],
    ['Рассчитываю на 200к в месяц.', '200'],
    ['Ожидаю 500k gross.', '500'],
    ['Ожидаю 400к на руки.', '400000'],
    ['Хочу 200к/мес.', '200'],
    ['Ожидаю ЗП 500К в месяц.', '500'],
    ['Ожидаю 200к долларов.', '200'],
    ['Ожидаю 80к в месяц.', '80000'],
    ['Ожидаю 400  тысяч рублей', '400000'],
  ])('неформальные тысячи и двойной пробел режутся (FU-13): «%s»', (answer, number) => {
    expect(validateAnswer(answer, { allowed: withResume })).toBe(`выдуманное число: ${number}`);
  });

  it.each([
    'ЗП 500', 'Заработная плата 500', '500 р.', '500 долларов', '500 $', '500 €', '500 евро',
    '500 gross', '500 net', '500 в месяц', '500/мес',
  ])('новые слова о деньгах снимают исключение для HTTP-кодов (FU-13): «%s»', (answer) => {
    expect(validateAnswer(answer, { allowed: real })).toBe('выдуманное число: 500');
  });

  it('слова, лишь похожие на деньги, исключение не снимают: «Европа», «сеть», «др.» (FU-13)', () => {
    expect(validateAnswer('Работал с партнёрами в Европе, разбирал коды 404 и 502.', { allowed: real })).toBeNull();
    expect(validateAnswer('Логи, метрики и др. — коды 500 и 503 в том числе.', { allowed: real })).toBeNull();
  });
});

describe('validateAnswer: вопрос о деньгах тоже снимает исключение для HTTP-кодов (G3)', () => {
  // Настоящие вопросы живого интервью 2026-09-15.
  const SALARY_Q = 'Какой у Вас желаемый уровень заработной платы?';
  const POSTMAN_Q = 'Расскажите, как Вы используете Postman или Curl в работе?';
  const real = allowedNumbers(['Зарплатная вилка: 180–260 тысяч рублей на руки.', SALARY_Q]);

  it.each([
    ['Ожидаю 500.', '500'],
    ['Ожидаю от 200.', '200'],
    ['Мои ожидания — 200–260.', '200'],
  ])('на вопрос о зарплате «%s» режется', (answer, number) => {
    expect(validateAnswer(answer, { allowed: real, question: SALARY_Q })).toBe(`выдуманное число: ${number}`);
  });

  it('без вопроса слов о деньгах в этих ответах нет — отсюда и дыра', () => {
    expect(validateAnswer('Ожидаю 500.', { allowed: real })).toBeNull();
  });

  it('на вопрос про Postman коды ответов по-прежнему проходят', () => {
    expect(validateAnswer('коды ответов 200, 400 и 500', { allowed: real, question: POSTMAN_Q })).toBeNull();
    expect(validateAnswer('Проверял коды ответов 200, 400 и 500.', { allowed: allowedNumbers([POSTMAN_Q]), question: POSTMAN_Q }))
      .toBeNull();
  });

  it.each([
    'Какой у вас желаемый заработок?',
    'Ваши ожидания по з/п?',
  ])('вопрос «%s» — тоже о деньгах', (question) => {
    expect(validateAnswer('Ожидаю 500.', { allowed: real, question })).toBe('выдуманное число: 500');
  });

  it('«з/п» и «заработок» в самом ответе снимают исключение; «из/под» — нет', () => {
    expect(validateAnswer('з/п 500', { allowed: real })).toBe('выдуманное число: 500');
    expect(validateAnswer('Мой заработок 500.', { allowed: real })).toBe('выдуманное число: 500');
    expect(validateAnswer('Работал из/под VPN, разбирал коды 404 и 502.', { allowed: real })).toBeNull();
  });

  // 400 есть в резюме («400 автотестов»): «400 к/мес» режется только по величине.
  const withResume = new Set([...real, ...allowedNumbers(['Внедрил 400 автотестов.'])]);

  it.each([
    ['Ожидаю 400 к/мес', '400000'],
    ['Ожидаю 400 к + бонусы', '400000'],
  ])('«к» через пробел перед «/» или «+» — тысячи: «%s» режется', (answer, number) => {
    expect(validateAnswer(answer, { allowed: withResume, question: SALARY_Q })).toBe(`выдуманное число: ${number}`);
  });
});
